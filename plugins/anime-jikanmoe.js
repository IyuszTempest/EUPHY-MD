/** * Plugin Jikan Moe (Anime Search)
 * Style: Euphylia Magenta - Ultimate UI
 */

const axios = require('axios');

module.exports = {
    command: ['jikanmoe', 'anime'],
    category: 'anime',
    noPrefix: true, 
    call: async (conn, m, { text, command, usedPrefix }) => {
        if (!text) return m.reply(`Mau cari anime apa hari ini? 🌸\nContoh: *${usedPrefix + command} tenten kakumei*`);

        // Reaksi loading biar estetik
        await conn.sendMessage(m.chat, { react: { text: '🔍', key: m.key } });

        try {
            // Memanggil API IyuszTempest
            const apiEndpoint = `https://iyusztempest.my.id/api/anime?feature=jikanmoe&query=${encodeURIComponent(text)}&apikey=${global.apiyus}`;
            const response = await axios.get(apiEndpoint);

            if (response.data.status !== "success" || !response.data.data.length) {
                return m.reply('Aduh, Euphy nggak nemu info animenya. Coba cek judulnya lagi ya! 🏮');
            }

            // Ambil hasil pertama yang paling relevan
            const data = response.data.data[0];
            
            let caption = `╭━━〔 ⛩️ *ANIME INFORMATION* ⛩️ 〕━━┓\n`
            caption += `┃ 🏮 *Judul:* ${data.title}\n`
            caption += `┃ 🇯🇵 *Japanese:* ${data.title_japanese || 'N/A'}\n`
            caption += `┃ ⭐ *Score:* ${data.score || 'N/A'}\n`
            caption += `┃ 🎞️ *Type:* ${data.type}\n`
            caption += `┃ 📅 *Status:* ${data.status}\n`
            caption += `┃ 🔢 *Episodes:* ${data.episodes || 'Unknown'}\n`
            caption += `┃ 🕒 *Duration:* ${data.duration}\n`
            caption += `┃ 🔞 *Rating:* ${data.rating}\n`
            caption += `┃ 🔗 *MAL URL:* ${data.url}\n`
            caption += `┗━━━━━━━━━━━━━━━━━┛\n\n`
            caption += `📖 *SYNOPSIS:*\n${data.synopsis ? data.synopsis.slice(0, 400) + '...' : 'Tidak ada sinopsis.'}\n\n`
            caption += `_Generated by Euphy System_`

            // Kirim poster dengan gaya Newsletter + AdReply
            await conn.sendMessage(m.chat, { 
                image: global.imgreply, 
                caption: caption,
                contextInfo: {
                    forwardingScore: 999,
                    isForwarded: true,
                    forwardedNewsletterMessageInfo: {
                        newsletterJid: global.idch,
                        newsletterName: `Anime Database - ${global.namech}`
                    },
                    externalAdReply: {
                        title: `Info: ${data.title}`,
                        body: `Season: ${data.season || 'N/A'} ${data.year || ''}`,
                        thumbnailUrl: data.images.jpg.image_url,
                        sourceUrl: data.url,
                        mediaType: 1,
                        renderLargerThumbnail: true
                    }
                }
            }, { quoted: m });

            await conn.sendMessage(m.chat, { react: { text: '✨', key: m.key } });

        } catch (e) {
            console.error(e);
            m.reply('Terjadi kesalahan saat menghubungi database anime. ❌');
            await conn.sendMessage(m.chat, { react: { text: '❌', key: m.key } });
        }
    }
};
                
